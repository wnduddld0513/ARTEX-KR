// localizeBackendError는 서버가 돌려준 오류 문구를 한국어로 바꾼다.
// 대응 항목이 없으면 원문을 그대로 돌려준다(진단 정보 보존).
export function localizeBackendError(message: string): string {
  const raw = message ?? "";
  const trimmed = raw.trim();
  if (!trimmed) return raw;
  // Object.prototype 상속 키("__proto__", "constructor", "toString" 등)를 오류 문구로
  // 착각하지 않도록 own property만 조회한다(알 수 없는 진단 문구는 원문 유지).
  const exact = Object.hasOwn(EXACT, trimmed) ? EXACT[trimmed] : undefined;
  if (exact) return exact;
  for (const [pattern, replacement] of PATTERNS) {
    if (pattern.test(trimmed)) return trimmed.replace(pattern, replacement);
  }
  for (const [prefix, replacement] of PREFIX) {
    if (trimmed.startsWith(prefix)) return replacement + trimmed.slice(prefix.length);
  }
  return raw;
}

// 복원된 아카이브가 사라졌다는 응답은 원문과 표시용 번역을 모두 인식한다.
export function isArchiveMissingError(message: string): boolean {
  const original = "归档不存在";
  return message.includes(original) || message.includes(localizeBackendError(original));
}
